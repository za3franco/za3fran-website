// ============================================================
// /api/validator-pdf.js — PDF copy of a Concept Validator v2 report (val-2.0.0 or later)
//   GET /api/validator-pdf?id=<validator_reports.id>&code=<access code>[&dl=1]
// The stored online report (fixed template, checked text, engine figures) rendered by headless Chrome with the
// fonts and logo embedded (lib/validator-pipeline.js embedForPdf): no network at render time, no model call.
// Access: the project's access code, same lockout as the viewers (5 attempts / 30 minutes).
// ============================================================

import { createClient } from '@supabase/supabase-js';
import CH from '../lib/bp-chrome.js';
import P from '../lib/validator-pipeline.js';

const supabase = createClient(process.env.SUPABASE_URL, process.env.SUPABASE_SERVICE_KEY);
const attempts = {};
const MAX_ATTEMPTS = 5;
const LOCKOUT_MS = 30 * 60 * 1000;
const slug = (s) => String(s || 'concept').normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-zA-Z0-9]+/g, '-').replace(/^-|-$/g, '').toLowerCase().slice(0, 40) || 'concept';

export default async function handler(req, res) {
  const id = String(req.query.id || '');
  const code = String(req.query.code || '').toUpperCase().trim();
  if (!id || !code) return res.status(400).send('Missing id or code');
  const t = attempts[id] || { n: 0, lockedAt: null };
  if (t.lockedAt && Date.now() - t.lockedAt < LOCKOUT_MS) return res.status(429).send('Too many attempts. Try again later.');

  const { data: row, error } = await supabase.from('validator_reports').select('id, access_code, report_html, report_json').eq('id', id).maybeSingle();
  if (error || !row) return res.status(404).send('Not found');
  if (code !== String(row.access_code || '').toUpperCase()) {
    t.n += 1; if (t.n >= MAX_ATTEMPTS) t.lockedAt = Date.now();
    attempts[id] = t;
    return res.status(403).send('Invalid code');
  }
  attempts[id] = { n: 0, lockedAt: null };
  const meta = (row.report_json && row.report_json.meta) || {};
  if (!row.report_html) return res.status(409).send('Report not generated yet');
  if (!/^val-2/.test(String(meta.generator || ''))) return res.status(409).json({ error: 'not_v2', detail: 'PDF copies exist for reports generated by the Validator v2.' });

  const started = Date.now();
  try {
    const pdf = await CH.withBrowser((browser) => CH.htmlToPdf(browser, P.embedForPdf(row.report_html)));
    console.log(`[validator-pdf] ${id} in ${Date.now() - started}ms, ${pdf.length} bytes`);
    const lang = meta.language === 'en' ? 'en' : 'fr';
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', `${req.query.dl ? 'attachment' : 'inline'}; filename="${slug(meta.concept_name)}-${lang === 'fr' ? 'rapport-validation' : 'validation-report'}.pdf"`);
    res.setHeader('Cache-Control', 'private, no-store');
    return res.status(200).send(Buffer.from(pdf));
  } catch (e) {
    console.error(`[validator-pdf] ${id} failed:`, e && e.stack ? e.stack : e);
    return res.status(500).send('Document failed: ' + (e && e.message ? e.message : 'unknown'));
  }
}
