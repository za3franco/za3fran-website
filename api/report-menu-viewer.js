// ============================================================
// /api/report-menu-viewer.js
// Access-code-gated viewer for the Menu Engineer Strategy Report.
// GET  ?id=xxx   → renders the access code gate
// POST { id, access_code } → validates code (or a valid session
//   cookie from a prior visit), then either:
//   - serves the strategy report, or
//   - triggers on-demand generation (fire-and-forget via waitUntil,
//     matching the BP Essentials v2 pattern) and renders a polling
//     loading page that auto-submits back here once ready.
//
// The strategy report is a full, self-contained HTML document
// generated by Claude (with its own print CSS per the locked
// pagination model). This viewer wraps it with a small navigation
// toolbar (hidden on print) linking to the Costing Workbook download.
// ============================================================

import { createClient } from '@supabase/supabase-js';
import { waitUntil } from '@vercel/functions';

const supabase = createClient(
  process.env.SUPABASE_URL,
  process.env.SUPABASE_SERVICE_KEY
);

const BASE_URL = process.env.NEXT_PUBLIC_BASE_URL || 'https://www.za3fran.io';

function parseCookies(header) {
  const list = {};
  if (!header) return list;
  header.split(';').forEach((part) => {
    const idx = part.indexOf('=');
    if (idx === -1) return;
    const name = part.slice(0, idx).trim();
    const value = part.slice(idx + 1).trim();
    if (name) list[name] = decodeURIComponent(value);
  });
  return list;
}

