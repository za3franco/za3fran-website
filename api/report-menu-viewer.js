// ── Toolbar injected into generated deliverable HTML ────────────
function injectToolbar(html, run, id, currentView) {
  const toolbar = `
<div class="za3fran-toolbar" style="position:sticky;top:0;z-index:999;background:#0F1F3D;color:#FAFAF7;padding:12px 24px;display:flex;gap:20px;align-items:center;font-family:'DM Sans',sans-serif;font-size:13px;flex-wrap:wrap;">
  <span style="font-family:'Cormorant Garamond',serif;font-size:16px;color:#C9862A;">Za3fran</span>
  <a href="/api/report-menu-viewer?id=${id}&view=report" style="color:${currentView === 'report' ? '#C9862A' : '#FAFAF7'};text-decoration:none;">Strategy Report</a>
  <a href="/api/report-menu-viewer?id=${id}&view=menu" style="color:${currentView === 'menu' ? '#C9862A' : '#FAFAF7'};text-decoration:none;">Branded Menu</a>
  ${run.output_xlsx_url ? `<a href="${run.output_xlsx_url}" style="color:#FAFAF7;text-decoration:none;" target="_blank">Download Costing Matrix (XLSX)</a>` : ''}
  <span style="margin-left:auto;color:#8b93a8;font-size:11px;">Use your browser's Print function to save as PDF</span>
</div>
<style>@media print { .za3fran-toolbar { display: none !important; } }</style>`;

  if (html.includes('<body')) {
    return html.replace(/<body([^>]*)>/i, `<body$1>${toolbar}`);
  }
  return toolbar + html;
}

// ── Main handler ────────────────────────────────────────────────
export default async function handler(req, res) {
  const source = req.method === 'GET' ? req.query : (req.body || {});
  const id = (source.id || '').toString().trim();
  const view = (source.view === 'menu') ? 'menu' : 'report';

  if (!id) {
    res.setHeader('Content-Type', 'text/html');
    return res.status(400).send(renderNotFound());
  }

  const { data: run, error: runError } = await supabase
    .from('menu_engineer_runs')
    .select('id, project_id, output_html, output_menu_html, output_xlsx_url, access_code, status, currency, language')
    .eq('id', id)
    .maybeSingle();

  if (runError || !run) {
    res.setHeader('Content-Type', 'text/html');
    return res.status(404).send(renderNotFound());
  }

  if (!run.access_code) {
    // Payment not yet processed by the webhook, or something went wrong upstream
    res.setHeader('Content-Type', 'text/html');
    return res.status(200).send(renderNotReady());
  }

  // ── GET: always show the access code gate ──────────────────
  if (req.method === 'GET') {
    res.setHeader('Content-Type', 'text/html');
    return res.status(200).send(renderGate(id, view, null));
  }

  // ── POST: validate access code ──────────────────────────────
  if (req.method !== 'POST') {
    return res.status(405).json({ error: 'Method not allowed' });
  }

  const suppliedCode = (source.access_code || '').toString().trim().toUpperCase();
  if (!suppliedCode || suppliedCode !== run.access_code) {
    res.setHeader('Content-Type', 'text/html');
    return res.status(401).send(renderGate(id, view, 'Incorrect access code. Please check your email and try again.'));
  }

  // ── Determine which content was requested ────────────────────
  const requestedHtml = view === 'menu' ? run.output_menu_html : run.output_html;

  if (requestedHtml) {
    res.setHeader('Content-Type', 'text/html');
    return res.status(200).send(injectToolbar(requestedHtml, run, id, view));
  }

  // ── Not generated yet — trigger generation if not already running ──
  if (run.status === 'pending_generation' || run.status === 'error') {
    await supabase
      .from('menu_engineer_runs')
      .update({ status: 'generating' })
      .eq('id', id);

    waitUntil(
      fetch(`${BASE_URL}/api/generate-menu`, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ runId: id }),
      }).catch((err) => console.error('[report-menu-viewer] Failed to trigger generation:', err))
    );
  }

  res.setHeader('Content-Type', 'text/html');
  return res.status(200).send(renderGenerating(id, suppliedCode, view));
}
