// ============================================================
// /api/report-menu-viewer.js
// Access-code-gated viewer for Menu Engineer deliverables.
// GET  ?id=xxx[&view=report|menu]  → renders the access code gate
// POST { id, access_code, view }   → validates code, then either:
//   - serves the requested deliverable (report or menu doc), or
//   - triggers on-demand generation (fire-and-forget via waitUntil,
//     matching the BP Essentials v2 pattern) and renders a polling
//     loading page that auto-submits back here once ready.
//
// The strategy report and branded menu document are both full,
// self-contained HTML documents generated by Claude (with their own
// print CSS per the locked pagination model). This viewer wraps them
// with a small navigation toolbar (hidden on print) rather than
// altering their content — the toolbar links between the report,
// the menu document, and the XLSX download.
// ============================================================

import { createClient } from '@supabase/supabase-js';
import { waitUntil } from '@vercel/functions';

const supabase = createClient(
  process.env.SUPABASE_URL,
  process.env.SUPABASE_SERVICE_KEY
);

const BASE_URL = process.env.NEXT_PUBLIC_BASE_URL || 'https://www.za3fran.io';

