-- Concept Studio lot 0: structured traits per format and archetypes per district (all researched, reviewed by Arnaud in /brain; never blocking)
create table if not exists brain_concept_traits(
 id uuid primary key default gen_random_uuid(),
 format_id uuid not null references brain_concept_formats(id) on delete cascade,
 trait text not null check (trait in ('archetypes','key_skill','beginner_difficulty','investor_needs_operator','extraction','alcohol','services','regulatory_flag','thin_sheet','proposable')),
 value text not null,
 line_id uuid references brain_concept_lines(id),
 inference boolean not null default false,
 status text not null default 'researched' check (status in ('researched','verified','superseded')),
 researched_by text default 'claude', reviewer text, reviewed_at timestamptz,
 created_at timestamptz default now(),
 unique(format_id, trait),
 check (line_id is not null or inference)
);
alter table brain_concept_traits enable row level security;
create table if not exists brain_district_archetypes(
 id uuid primary key default gen_random_uuid(),
 market_id uuid not null references brain_markets(id) on delete cascade,
 archetype text not null check (archetype in ('A','B','C','D','E')),
 rank smallint not null default 1,
 basis_note_id uuid references brain_district_notes(id),
 inference boolean not null default true,
 note text,
 status text not null default 'researched' check (status in ('researched','verified','superseded')),
 reviewer text, reviewed_at timestamptz, created_at timestamptz default now(),
 unique(market_id, archetype)
);
alter table brain_district_archetypes enable row level security;

