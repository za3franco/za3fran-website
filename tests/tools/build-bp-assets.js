/* Dev tool (not deployed: tests/ is in .vercelignore).
 * Builds lib/bp-assets.js: the brand fonts (Cormorant Garamond, DM Sans — SIL OFL, from the @fontsource npm
 * packages) and the logo (transparent copper PNG) embedded as base64, so the server-side PDF never depends on
 * Google Fonts being reachable at render time.
 * Usage: node tests/tools/build-bp-assets.js <dir containing node_modules/@fontsource> <logo-copper.png>
 */
'use strict';
const fs = require('fs');
const path = require('path');
const [, , base, logo] = process.argv;
if (!base || !logo) { console.error('usage: node build-bp-assets.js <fontsource base dir> <logo png>'); process.exit(1); }
const FONTS = [
  ['Cormorant Garamond', 'cormorant-garamond', 500, 'normal'], ['Cormorant Garamond', 'cormorant-garamond', 600, 'normal'], ['Cormorant Garamond', 'cormorant-garamond', 500, 'italic'],
  ['DM Sans', 'dm-sans', 400, 'normal'], ['DM Sans', 'dm-sans', 500, 'normal'], ['DM Sans', 'dm-sans', 700, 'normal'],
];
const faces = FONTS.map(([family, pkg, weight, style]) => {
  // latin + latin-ext cover French (œ, é, ç, …) and the typographic punctuation used in the plans
  const files = ['latin', 'latin-ext'].map((subset) => path.join(base, 'node_modules/@fontsource', pkg, 'files', `${pkg}-${subset}-${weight}-${style}.woff2`));
  return files.filter((f) => fs.existsSync(f)).map((f, i) => ({ family, weight, style, subset: i === 0 ? 'latin' : 'latin-ext', b64: fs.readFileSync(f).toString('base64') }));
}).flat();
const logoB64 = fs.readFileSync(logo).toString('base64');
const out = `/* lib/bp-assets.js — GENERATED by tests/tools/build-bp-assets.js (do not edit by hand).
 * Brand fonts (SIL Open Font License) and logo, embedded for the server-side PDF and the deck. */
'use strict';
const FACES = ${JSON.stringify(faces)};
const RANGE = { latin: 'U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF,U+FFFD', 'latin-ext': 'U+0100-02BA,U+02BD-02C5,U+02C7-02CC,U+02CE-02D7,U+02DD-02FF,U+0304,U+0308,U+0329,U+1D00-1DBF,U+1E00-1E9F,U+1EF2-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,U+2C60-2C7F,U+A720-A7FF' };
const fontCss = FACES.map((f) => \`@font-face{font-family:'\${f.family}';font-style:\${f.style};font-weight:\${f.weight};font-display:block;src:url(data:font/woff2;base64,\${f.b64}) format('woff2');unicode-range:\${RANGE[f.subset]};}\`).join('\\n');
const logoDataUri = 'data:image/png;base64,${logoB64}';
module.exports = { fontCss, logoDataUri };
`;
fs.writeFileSync(path.join(__dirname, '../../lib/bp-assets.js'), out);
console.log('lib/bp-assets.js', Math.round(out.length / 1024) + ' KB', faces.length + ' font files');
